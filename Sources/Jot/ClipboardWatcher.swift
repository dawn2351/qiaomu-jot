import AppKit

/// Remembers when the clipboard last changed and in which app, so ⌘⇧K with nothing selected
/// can save what was just copied (text, images, video, files) — each copy only once.
final class ClipboardWatcher {
    static let shared = ClipboardWatcher()

    private let pb: NSPasteboard
    private var count: Int
    init(pasteboard: NSPasteboard = .general) {
        pb = pasteboard
        count = pasteboard.changeCount
    }
    private var consumed = -1
    private(set) var changedAt: Date?
    private var sourceBundleID: String?
    private var sourceName: String?
    private var timer: Timer?

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.75, repeats: true) { [weak self] _ in self?.tick() }
        timer?.tolerance = 0.25
    }

    private static let ignoredTypes = ["org.nspasteboard.TransientType", "org.nspasteboard.ConcealedType",
                                       "org.nspasteboard.AutoGeneratedType"].map { NSPasteboard.PasteboardType($0) }

    private func tick() {
        guard pb.changeCount != count else { return }
        count = pb.changeCount
        // Password managers and our own clipboard restores mark themselves; never treat those as a copy.
        if (pb.types ?? []).contains(where: Self.ignoredTypes.contains) { changedAt = nil; return }
        changedAt = Date()
        let app = NSWorkspace.shared.frontmostApplication
        sourceBundleID = app?.bundleIdentifier
        sourceName = app?.localizedName
    }

    struct Clip {
        var grabbed: Grabbed
        var context: SourceContext?
        /// nil when the copy happened before the app started watching.
        var date: Date?
        var kindLabel: String {
            if !grabbed.files.isEmpty { return grabbed.files.count > 1 ? "\(grabbed.files.count) 个文件" : "文件" }
            if let m = grabbed.media.first { return ["mp4", "mov"].contains(m.ext) ? "视频" : "图片" }
            return "文字"
        }
    }

    /// Clipboard content not saved yet. `within` limits it to recent copies.
    func clip(within: TimeInterval? = nil) -> Clip? {
        tick()
        guard count != consumed, !(pb.types ?? []).contains(where: Self.ignoredTypes.contains) else { return nil }
        if let within { guard let d = changedAt, Date().timeIntervalSince(d) < within else { return nil } }
        let g = SelectionGrabber.read(pb)
        guard !g.isEmpty, !g.concealed else { return nil }
        let ctx = changedAt == nil ? nil : sourceBundleID.map {
            SourceContext(appName: sourceName ?? $0, bundleID: $0, kind: SourceContext.kind(for: $0), pid: 0)
        }
        return Clip(grabbed: g, context: ctx, date: changedAt)
    }

    func consume() { consumed = pb.changeCount }
}

/// The newest screenshot / screen recording file macOS just saved (⇧⌘3/4/5).
enum ScreenshotFinder {
    private static var consumed = Set<String>()
    private static let prefixes = ["截屏", "截图", "屏幕快照", "屏幕录制", "录屏", "Screenshot", "Screen Shot", "Screen Recording", "CleanShot"]

    static var folder: URL {
        let custom = UserDefaults(suiteName: "com.apple.screencapture")?.string(forKey: "location")
        return custom.map { URL(fileURLWithPath: ($0 as NSString).expandingTildeInPath, isDirectory: true) }
            ?? FileManager.default.homeDirectoryForCurrentUser.appendingPathComponent("Desktop", isDirectory: true)
    }

    static func latest(in dir: URL = folder, within: TimeInterval = 300) -> (url: URL, date: Date)? {
        guard let files = try? FileManager.default.contentsOfDirectory(
            at: dir, includingPropertiesForKeys: [.creationDateKey], options: [.skipsHiddenFiles]) else { return nil }
        return files.compactMap { u -> (URL, Date)? in
            guard prefixes.contains(where: { u.lastPathComponent.hasPrefix($0) }), !consumed.contains(u.path),
                  ["png", "jpg", "jpeg", "heic", "tiff", "gif", "mov", "mp4"].contains(u.pathExtension.lowercased()),
                  let d = try? u.resourceValues(forKeys: [.creationDateKey]).creationDate,
                  Date().timeIntervalSince(d) < within else { return nil }
            return (u, d)
        }.max { $0.1 < $1.1 }
    }

    static func consume(_ url: URL) { consumed.insert(url.path) }
}
